#!/usr/bin/env node
/**
 * scripts/build-redirects.mjs
 *
 * Writes the rules in src/data/redirects.js into BOTH netlify.toml and
 * public/_redirects, so the redirects survive either deploy path:
 * a git-based Netlify build (reads netlify.toml) or a manual upload of a
 * prebuilt dist (only dist/_redirects travels with the files).
 *
 * Runs as part of `yarn build`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { REDIRECTS as RAW_REDIRECTS } from "../src/data/redirects.js";

const ROOT = fileURLToPath(new URL("../", import.meta.url));

/**
 * A rule like `/a/*` -> `/a` is circular: `/a/*` also matches `/a/` with an
 * empty splat, and the target `/a` normalises back to `/a/`, so Netlify sees a
 * loop and silently drops the rule. That is why the retired URLs kept 404ing
 * while a rule such as `/calculators/bmi/age/*` -> `/calculators/bmi`, whose
 * target sits outside its own pattern, worked fine.
 *
 * Expanding into `/a/:seg` and `/a/:seg/*` fixes it: `:seg` requires a
 * non-empty path segment, so neither `/a` nor `/a/` can match, and the two
 * rules together still cover one-or-more extra segments.
 */
const expand = (rules) =>
  rules.flatMap((rule) => {
    const base = rule.from.endsWith("/*") ? rule.from.slice(0, -2) : null;
    if (!base || base !== rule.to) return [rule];
    return [
      { ...rule, from: `${base}/:seg` },
      { ...rule, from: `${base}/:seg/*` },
    ];
  });

const REDIRECTS = expand(RAW_REDIRECTS);

const WARNING = `Generated by scripts/build-redirects.mjs from src/data/redirects.js.
Do not edit by hand - your changes will be overwritten by the next build.

There is deliberately no "/*" catch-all: a rule sending every unmatched URL
to /index.html with status 200 served the homepage as a soft 404 for any URL
that did not exist, and overrode every other rule.`;

/* ---------------- netlify.toml ---------------- */
const tomlPath = path.join(ROOT, "netlify.toml");
const existing = fs.readFileSync(tomlPath, "utf8");
// Keep whatever comes before the first [[redirects]] block (the [build] table).
const head = existing.split("[[redirects]]")[0].replace(/#\s*-+\n(#.*\n)*/g, "").trimEnd();

const toml =
  head +
  "\n\n" +
  WARNING.split("\n").map((l) => (l ? `# ${l}` : "#")).join("\n") +
  "\n\n" +
  REDIRECTS.map(
    (r) => `[[redirects]]\n  from = "${r.from}"\n  to = "${r.to}"\n  status = ${r.status}\n`
  ).join("\n");
fs.writeFileSync(tomlPath, toml);

/* ---------------- public/_redirects ---------------- */
const width = Math.max(...REDIRECTS.map((r) => r.from.length)) + 2;
const redirects =
  WARNING.split("\n").map((l) => (l ? `# ${l}` : "#")).join("\n") +
  "\n\n" +
  REDIRECTS.map((r) => `${r.from.padEnd(width)}${r.to}  ${r.status}`).join("\n") +
  "\n";
fs.writeFileSync(path.join(ROOT, "public/_redirects"), redirects);

console.log(`Wrote ${REDIRECTS.length} redirect rules to netlify.toml and public/_redirects`);
